"""Generate firmware/app/main/eq_tables.inc: integer (Q28) biquad coefficients for the 7-band EQ.

The speaker runs no floating point in its audio path, so every coefficient is designed here in
double precision (RBJ audio-EQ cookbook) and stored as int32 Q28. Rows: rate x band x gain
(-12..+12 dB) x {b0, b1, b2, a1, a2} (a0 normalised to 1). Band 0 is a low shelf, band 6 a high
shelf (slope 1), the rest are peaking filters with Q = 1.1 (about 1.3 octaves, matching the
band spacing). Preamp: 10^(-peak/40) in Q30 for the largest boost 0..12 dB (half of it in dB).
"""
import math, pathlib
RATES = [16000, 32000, 44100, 48000]
FREQS = [63, 160, 400, 1000, 2500, 6300, 16000]
PEAK_Q = 1.1
def design(rate, band, gain):
    A = 10 ** (gain / 40); f = min(FREQS[band], 0.45 * rate); w = 2 * math.pi * f / rate
    cw, sw = math.cos(w), math.sin(w)
    if band in (0, len(FREQS) - 1):
        al = sw / 2 * math.sqrt(2); sa = 2 * math.sqrt(A) * al
        if band == 0:
            b0 = A * ((A + 1) - (A - 1) * cw + sa); b1 = 2 * A * ((A - 1) - (A + 1) * cw); b2 = A * ((A + 1) - (A - 1) * cw - sa)
            a0 = (A + 1) + (A - 1) * cw + sa; a1 = -2 * ((A - 1) + (A + 1) * cw); a2 = (A + 1) + (A - 1) * cw - sa
        else:
            b0 = A * ((A + 1) + (A - 1) * cw + sa); b1 = -2 * A * ((A - 1) + (A + 1) * cw); b2 = A * ((A + 1) + (A - 1) * cw - sa)
            a0 = (A + 1) - (A - 1) * cw + sa; a1 = 2 * ((A - 1) - (A + 1) * cw); a2 = (A + 1) - (A - 1) * cw - sa
    else:
        al = sw / (2 * PEAK_Q)
        b0 = 1 + al * A; b1 = -2 * cw; b2 = 1 - al * A; a0 = 1 + al / A; a1 = -2 * cw; a2 = 1 - al / A
    return [round(v / a0 * 2 ** 28) for v in (b0, b1, b2, a1, a2)]
def response_db(c, rate, f):
    z = complex(math.cos(2 * math.pi * f / rate), math.sin(2 * math.pi * f / rate)); zi = 1 / z
    num = c[0] + c[1] * zi + c[2] * zi * zi; den = 2 ** 28 + c[3] * zi + c[4] * zi * zi
    return 20 * math.log10(abs(num / den))
out = ['/* Generated by tools/gen_eq_tables.py - do not edit. Q28 biquads, see the generator. */',
       f'#define WMP_EQ_RATE_COUNT {len(RATES)}u',
       'static const uint32_t eq_rates[WMP_EQ_RATE_COUNT]={' + ','.join(f'{r}u' for r in RATES) + '};',
       'static const uint16_t eq_band_hz[WMP_EQ_BANDS]={' + ','.join(map(str, FREQS)) + '};',
       'static const int32_t eq_table[WMP_EQ_RATE_COUNT][WMP_EQ_BANDS][25][5]={']
worst = 0
for r in RATES:
    out.append(' {')
    for b in range(len(FREQS)):
        rows = []
        for g in range(-12, 13):
            c = design(r, b, g); assert all(abs(v) < 2 ** 31 for v in c)
            if FREQS[b] < 0.45 * r and 0 < b < len(FREQS) - 1:
                worst = max(worst, abs(response_db(c, r, FREQS[b]) - g))   # peak gain at its centre
            rows.append('{' + ','.join(map(str, c)) + '}')
        out.append('  {' + ','.join(rows) + '},')
    out.append(' },')
out.append('};')
out.append('static const int32_t eq_preamp_q30[13]={' + ','.join(str(round(2 ** 30 * 10 ** (-p / 40))) for p in range(13)) + '};')
path = pathlib.Path(__file__).resolve().parents[1] / 'firmware/app/main/eq_tables.inc'
path.write_text('\n'.join(out) + '\n')
print(f'wrote {path} ({path.stat().st_size} bytes); worst peak-gain error at centre {worst:.4f} dB')
